import { readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runMoon, verifyMoonVersion } from './moon-toolchain.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const start = '<!-- MOONBIT_CORE_START -->';
const end = '<!-- MOONBIT_CORE_END -->';
try {
  verifyMoonVersion({ cwd: root });
  runMoon(['build', '--target', 'js', 'moonbit/core'], { cwd: root });
  const [html, bundle] = await Promise.all([readFile(join(root, 'index.html'), 'utf8'), readFile(join(root, '_build/js/debug/build/core/core.js'), 'utf8')]);
  if (html.split(start).length !== 2 || html.split(end).length !== 2 || html.indexOf(start) > html.indexOf(end)) throw new Error('Expected exactly one ordered pair of MoonBit generated-output markers in index.html.');
  const actual = html.slice(html.indexOf(start) + start.length, html.indexOf(end)).trim();
  const expected = `<script>/* Generated by npm run build from moonbit/core. */\n${bundle}</script>`;
  if (actual !== expected) throw new Error('MoonBit output is stale. Run npm run build and commit the resulting index.html.');
  const generated = ['index.html', 'assets/runtime/anatomy-registry.js', 'assets/runtime/root-scm-runtime.js'];
  const before = await Promise.all(generated.map((file) => readFile(join(root, file))));
  for (const script of ['scripts/build-anatomy-registry-runtime.mjs', 'scripts/build-root-scm-runtime.mjs']) execFileSync(process.execPath, [script], { cwd: root, stdio: 'inherit' });
  const after = await Promise.all(generated.map((file) => readFile(join(root, file))));
  if (before.some((artifact, index) => !artifact.equals(after[index]))) throw Error(`Generated artifacts are stale. Run npm run build and commit: ${generated.join(', ')}.`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
