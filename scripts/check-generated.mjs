import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runMoon, verifyMoonVersion } from './moon-toolchain.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const start = '<!-- MOONBIT_CORE_START -->';
const end = '<!-- MOONBIT_CORE_END -->';
try {
  verifyMoonVersion({ cwd: root });
  for (const pkg of ['moonbit/motion', 'moonbit/anatomy', 'moonbit/agent', 'moonbit/zhnum']) {
    const interfacePath = join(root, pkg, 'pkg.generated.mbti');
    const interfaceBefore = await readFile(interfacePath, 'utf8');
    runMoon(['info', pkg, '--target', 'js'], { cwd: root });
    const interfaceAfter = await readFile(interfacePath, 'utf8');
    if (interfaceBefore.replace(/\r\n/g, '\n') !== interfaceAfter.replace(/\r\n/g, '\n')) throw Error(`MoonBit public interface is stale. Run moon info ${pkg} --target js and review the API change.`);
  }
  runMoon(['build', '--target', 'js', 'moonbit/core'], { cwd: root });
  const [html, bundle, externalBundle] = await Promise.all([
    readFile(join(root, 'index.html'), 'utf8'),
    readFile(join(root, '_build/js/debug/build/core/core.js'), 'utf8'),
    readFile(join(root, 'assets/runtime/moonbit-core.js'), 'utf8'),
  ]);
  if (html.split(start).length !== 2 || html.split(end).length !== 2 || html.indexOf(start) > html.indexOf(end)) throw new Error('Expected exactly one ordered pair of MoonBit generated-output markers in index.html.');
  const actual = html.slice(html.indexOf(start) + start.length, html.indexOf(end)).trim();
  const expected = '<script src="assets/runtime/moonbit-core.js"></script>';
  if (actual !== expected) throw new Error('index.html must load the generated MoonBit bundle as one external script.');
  const expectedBundle = `/* Generated by npm run build from moonbit/core. */\n${bundle}`;
  if (externalBundle.replace(/\r\n/g, '\n') !== expectedBundle.replace(/\r\n/g, '\n')) throw new Error('MoonBit output is stale. Run npm run build and commit assets/runtime/moonbit-core.js.');
  const generated = ['index.html', 'assets/runtime/moonbit-core.js', 'generated/anatomy-registry.json', 'src/anatomy/neck-registry.mjs', 'src/anatomy/full-muscle-registry.mjs', 'assets/anatomy/human-atlas/full-muscles.glb', 'assets/anatomy/human-atlas/full-muscles.manifest.json', 'assets/anatomy/human-atlas/FULL_BODY_ATTRIBUTION.md', 'assets/runtime/anatomy-registry.js', 'assets/runtime/coach-query-runtime.js', 'assets/runtime/root-scm-runtime.js', 'assets/runtime/full-muscle-runtime.js'];
  generated.push('assets/runtime/rigged-body-offline.js');
  generated.push('assets/presentation/head-surface.json');
  const before = await Promise.all(generated.map((file) => readFile(join(root, file))));
  const rigFiles = ['assets/anatomy/human-atlas/rigged-body.glb', 'assets/anatomy/human-atlas/rigged-body.manifest.json'];
  const rigBefore = await Promise.all(rigFiles.map((file) => readFile(join(root, file))));
  execFileSync(process.execPath, ['scripts/build-rigged-body.mjs'], { cwd: root, stdio: 'inherit' });
  const rigAfter = await Promise.all(rigFiles.map((file) => readFile(join(root, file))));
  if (rigBefore.some((artifact, index) => !artifact.equals(rigAfter[index]))) throw Error('Rigged anatomy assets are stale. Run npm run anatomy:build-rig.');
  for (const script of ['scripts/build-moonbit-registry.mjs', 'scripts/build-anatomy-registry-runtime.mjs', 'scripts/build-coach-query-runtime.mjs', 'scripts/build-root-scm-runtime.mjs', 'scripts/build-full-muscle-runtime.mjs']) execFileSync(process.execPath, [script], { cwd: root, stdio: 'inherit' });
  execFileSync(process.execPath, ['scripts/build-human-atlas-full.mjs', '--from-committed'], { cwd: root, stdio: 'inherit' });
  const after = await Promise.all(generated.map((file) => readFile(join(root, file))));
  const normalizeLineEndings = (artifact) => artifact.toString('utf8').replace(/\r\n/g, '\n');
  if (before.some((artifact, index) => normalizeLineEndings(artifact) !== normalizeLineEndings(after[index]))) throw Error(`Generated artifacts are stale. Run npm run build and commit: ${generated.join(', ')}.`);
  // Builders write LF. Preserve a CRLF checkout when the only difference is line endings.
  await Promise.all(before.map((artifact, index) => artifact.equals(after[index]) ? null : writeFile(join(root, generated[index]), artifact)));
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
